// Command scopegen turns the x-hashi-* operation extensions in api/openapi.yaml into the table the scope middleware
// enforces (01-platform.md §7). It fails when an operation does not declare x-hashi-scopes.
package main

import (
	"bytes"
	"fmt"
	"go/format"
	"os"
	"slices"
	"strings"

	"go.yaml.in/yaml/v3"
)

type operation struct {
	OperationID string   `yaml:"operationId"`
	Scopes      []string `yaml:"x-hashi-scopes"`
	HasScopes   bool     `yaml:"-"`
	Session     bool     `yaml:"x-hashi-session"`
	Reauth      bool     `yaml:"x-hashi-reauth"`
}

func main() {
	if len(os.Args) != 3 {
		fmt.Fprintln(os.Stderr, "usage: scopegen <openapi.yaml> <out.go>")
		os.Exit(2)
	}
	if err := run(os.Args[1], os.Args[2]); err != nil {
		fmt.Fprintln(os.Stderr, "scopegen:", err)
		os.Exit(1)
	}
}

func run(in, out string) error {
	raw, err := os.ReadFile(in) //nolint:gosec // build tool, path from the Makefile
	if err != nil {
		return err
	}
	var doc struct {
		Paths map[string]map[string]yaml.Node `yaml:"paths"`
	}
	if err := yaml.Unmarshal(raw, &doc); err != nil {
		return err
	}
	methods := []string{"get", "put", "post", "delete", "patch", "head", "options"}
	var ops []operation
	for path, items := range doc.Paths {
		for m, node := range items {
			if !slices.Contains(methods, m) {
				continue
			}
			var op operation
			if err := node.Decode(&op); err != nil {
				return fmt.Errorf("%s %s: %w", m, path, err)
			}
			var probe map[string]any
			_ = node.Decode(&probe)
			if _, ok := probe["x-hashi-scopes"]; !ok {
				return fmt.Errorf("%s %s: missing x-hashi-scopes", m, path)
			}
			if op.OperationID == "" {
				return fmt.Errorf("%s %s: missing operationId", m, path)
			}
			ops = append(ops, op)
		}
	}
	slices.SortFunc(ops, func(a, b operation) int { return strings.Compare(a.OperationID, b.OperationID) })
	var b bytes.Buffer
	b.WriteString("// Code generated by scopegen from api/openapi.yaml. DO NOT EDIT.\n\npackage gen\n\n")
	b.WriteString("// Requirement is what an operation needs from the caller's admin session.\n")
	b.WriteString("type Requirement struct {\n\tScopes []string\n\tSession bool\n\tReauth bool\n}\n\n")
	b.WriteString("// NeedsSession reports whether the operation rejects anonymous callers.\n")
	b.WriteString("func (r Requirement) NeedsSession() bool { return r.Session || r.Reauth || len(r.Scopes) > 0 }\n\n")
	b.WriteString("// Requirements is keyed by the operation name passed to strict middleware.\n")
	b.WriteString("var Requirements = map[string]Requirement{\n")
	for _, op := range ops {
		name := strings.ToUpper(op.OperationID[:1]) + op.OperationID[1:]
		fmt.Fprintf(&b, "\t%q: {Scopes: %#v, Session: %t, Reauth: %t},\n", name, nonNil(op.Scopes), op.Session, op.Reauth)
	}
	b.WriteString("}\n")
	src, err := format.Source(b.Bytes())
	if err != nil {
		return err
	}
	return os.WriteFile(out, src, 0o644) //nolint:gosec // generated source file
}

func nonNil(s []string) []string {
	if s == nil {
		return []string{}
	}
	return s
}
